// Все события конкретного дня и зала, отсортированные по времени начала.
export function sessionsFor(day: string, hall: Hall): SessionBlock[] {
    return PROGRAM
        .filter((s) => s.day === day && s.hall === hall)
        .sort((a, b) => a.start.localeCompare(b.start));
}

// Залы, в которых в указанный день есть события.
export function hallsWithEvents(day: string): Hall[] {
    return HALLS.filter((h) => PROGRAM.some((s) => s.day === day && s.hall === h));
}
